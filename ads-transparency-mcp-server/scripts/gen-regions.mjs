// Generates src/data/regions.ts: ISO 3166-1 alpha-2 -> Google Ads geo target ID.
// Rule verified against live Ads Transparency Center responses: id = 2000 + ISO numeric,
// with the exceptions listed below.
import countries from "i18n-iso-countries";
import en from "i18n-iso-countries/langs/en.json" with { type: "json" };
import fr from "i18n-iso-countries/langs/fr.json" with { type: "json" };
import fs from "node:fs";
countries.registerLocale(en);
countries.registerLocale(fr);
const EXCEPTIONS = { IM: 20340 };
const rows = [];
for (const [a2, num] of Object.entries(countries.getAlpha2Codes()).map(([a2]) => [a2, countries.alpha2ToNumeric(a2)])) {
  if (!num) continue;
  const id = EXCEPTIONS[a2] ?? 2000 + Number(num);
  const nameEn = countries.getName(a2, "en", { select: "official" }) ?? a2;
  const nameFr = countries.getName(a2, "fr", { select: "official" }) ?? nameEn;
  rows.push([a2, id, nameEn, nameFr]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));
const body = rows.map(([a2, id, e, f]) => `  ${a2}: { id: ${id}, en: ${JSON.stringify(e)}, fr: ${JSON.stringify(f)} },`).join("\n");
const out = `// Generated by scripts/gen-regions.mjs. Do not edit by hand.
// ISO 3166-1 alpha-2 code -> Google Ads geo target ID used by the Ads Transparency Center.
export interface RegionInfo {
  id: number;
  en: string;
  fr: string;
}

export const REGIONS: Record<string, RegionInfo> = {
${body}
};
`;
fs.writeFileSync("src/data/regions.ts", out);
console.log("regions:", rows.length);
